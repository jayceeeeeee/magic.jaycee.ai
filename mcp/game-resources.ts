import {
  JAYCEE_GAME_CONFIG,
  JAYCEE_GAME_CYCLE_LABELS,
  JAYCEE_GAME_SKILL_COLUMNS,
} from "../src/js/config/game-config.js";
import {
  getMannaModel,
  getMannaRules,
  getMannaSkillModels,
} from "../src/js/config/manna.js";

export function getGameConfig() {
  const practiceModels = getMannaSkillModels();
  return {
    game_config: JAYCEE_GAME_CONFIG,
    skill_columns: JAYCEE_GAME_SKILL_COLUMNS,
    cycle_labels: JAYCEE_GAME_CYCLE_LABELS,
    manna_rules: getMannaRules(),
    practice_goal_rule:
      "For active skill at zero-based index i: target_seconds = passive.cycleSeconds / product(activeAbilities[0..i].ratio).",
    practice_goal_targets: JAYCEE_GAME_CONFIG.activeAbilities.map(
      (ability, index) => {
        const targetSeconds = practiceModels[index].questSeconds;
        const roundedSeconds = Math.round(targetSeconds);
        const hours = Math.floor(roundedSeconds / 3600);
        const minutes = Math.floor((roundedSeconds % 3600) / 60);
        const seconds = roundedSeconds % 60;
        return {
          skill_number: index + 1,
          skill_column: ability.skillColumn,
          fractal_label: ability.fractalLabel,
          associated_cycle: JAYCEE_GAME_CYCLE_LABELS.activeAbilities[index],
          target_seconds: targetSeconds,
          target_display: [
            hours ? `${hours} h` : "",
            minutes ? `${minutes} min` : "",
            seconds ? `${seconds} s` : "",
          ]
            .filter(Boolean).join(" "),
        };
      },
    ),
  };
}

// These are synthetic worked examples, executed by the game's actual engine.
// No connected user's settings or records are read or embedded in resources.
export function getMannaExamples() {
  const now = new Date("2026-01-01T00:00:00.000Z");
  const activeModels = getMannaSkillModels();
  const playerProfile = {
    manna_target: 240,
    manna_cycle: "day",
    manna_unit: "EUR",
  };
  const active = activeModels.map((model, index) => {
    const skillNumber = index + 1;
    const player = {
      id: "example-player",
      level: 4,
      [`skill_${skillNumber}_start`]: new Date(
        now.getTime() - model.passiveSeconds * 500,
      ).toISOString(),
      [`skill_${skillNumber}_practice`]: model.questSeconds / 4,
    };
    return {
      title:
        `Skill ${skillNumber}: one quarter of the practice goal, halfway through its cycle`,
      input: {
        player_profile: playerProfile,
        player,
        selected_skill: skillNumber,
        now: now.toISOString(),
        time_zone: "UTC",
      },
      result: getMannaModel({
        activeModels,
        player,
        playerProfile,
        now,
        timeZone: "UTC",
        selectedAbilityIndex: skillNumber,
      }),
    };
  });
  const accountCreatedAt = new Date(
    now.getTime() - JAYCEE_GAME_CONFIG.passive.cycleSeconds * 500,
  ).toISOString();
  const completedPassiveSeconds = activeModels[0].passiveSeconds * 2;
  const player = {
    id: "example-player",
    level: 4,
    skill_3_practice: activeModels[2].questSeconds / 2,
  };
  return {
    synthetic: true,
    description:
      "Results are generated by getMannaModel and getMannaRules, the same functions used by the game and MCP tools. These examples are explanations, not personal balances.",
    active_cycles: active,
    annual_overview: {
      title:
        "Annual overview with two archived skill-1 goals and half of the skill-3 goal",
      input: {
        player_profile: playerProfile,
        player,
        account_created_at: accountCreatedAt,
        completed_passive_seconds: completedPassiveSeconds,
        now: now.toISOString(),
        time_zone: "UTC",
      },
      result: getMannaModel({
        activeModels,
        player,
        playerProfile,
        accountCreatedAt,
        completedPassiveSeconds,
        now,
        timeZone: "UTC",
        selectedAbilityIndex: 0,
      }),
    },
    calendar_month: {
      title:
        "Calendar-month normalization across the March daylight-saving change in Paris",
      input: {
        player_profile: {
          manna_target: 310,
          manna_cycle: "month",
          manna_unit: "EUR",
        },
        reference_at: "2026-03-15T00:00:00.000Z",
        time_zone: "Europe/Paris",
      },
      result: getMannaRules(
        { manna_target: 310, manna_cycle: "month", manna_unit: "EUR" },
        new Date("2026-03-15T00:00:00.000Z"),
        "Europe/Paris",
      ),
    },
  };
}

