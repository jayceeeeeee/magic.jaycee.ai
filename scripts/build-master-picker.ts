// Commit the generated HTML module so Edge deployment has no frontend imports.
export async function buildMasterPicker(check = false, game = false) {
  const root = new URL("../", import.meta.url);
  const entry = new URL(
    game ? "mcp/ui/game.js" : "mcp/ui/master-picker.js",
    root,
  );
  const output = new URL(
    game
      ? "supabase/functions/game-mcp/resource-game.generated.ts"
      : "supabase/functions/game-mcp/resource-master-picker.generated.ts",
    root,
  );
  const inputs = new Map<string, Uint8Array>();
  const decoder = new TextDecoder();
  async function visit(url: URL) {
    if (inputs.has(url.href)) return;
    const raw = await Deno.readFile(url);
    // Git may check text out as CRLF on Windows. Hash logical source content.
    const bytes = /\.(?:js|ts|css)$/.test(url.pathname)
      ? new TextEncoder().encode(decoder.decode(raw).replaceAll("\r\n", "\n"))
      : raw;
    inputs.set(url.href, bytes);
    if (!url.pathname.endsWith(".js")) return;
    const source = decoder.decode(bytes);
    for (const match of source.matchAll(/\bfrom\s*["'](\.[^"']+)["']/g)) {
      await visit(new URL(match[1], url));
    }
    for (const match of source.matchAll(/\bimport\s*["'](\.[^"']+)["']/g)) {
      await visit(new URL(match[1], url));
    }
    for (const match of source.matchAll(/["'](\/src\/assets\/[^"']+)["']/g)) {
      await visit(new URL(`.${match[1]}`, root));
    }
  }
  await visit(entry);
  await visit(new URL(import.meta.url));
  await visit(new URL("game.html", root));
  const styles = [
    "src/css/global.css",
    "src/css/game-fonts.css",
    "src/css/game-ui.css",
    "src/css/master-picker.css",
    ...(game ? ["src/css/game.css"] : []),
  ];
  for (const name of styles) await visit(new URL(name, root));
  const hashes = [];
  for (
    const [url, bytes] of [...inputs].sort(([a], [b]) => a.localeCompare(b))
  ) {
    const digest = await crypto.subtle.digest("SHA-256", bytes);
    hashes.push(
      url.slice(root.href.length) + ":" +
        [...new Uint8Array(digest)].map((n) => n.toString(16).padStart(2, "0"))
          .join(""),
    );
  }
  const stamp = `// Inputs: ${JSON.stringify(hashes)}\n`;
  const previous = await Deno.readTextFile(output).catch(() => "");
  if (check) {
    if (!previous.startsWith(stamp)) {
      throw new Error(
        "Stale MCP Master picker. Run scripts/build-master-picker.ts.",
      );
    }
    if (game) {
      const shared = await Deno.readTextFile(
        new URL(
          "supabase/functions/game-mcp/resource-ui-assets.generated.ts",
          root,
        ),
      ).catch(() => "");
      if (!shared.startsWith(stamp)) {
        throw new Error(
          "Stale shared MCP assets. Run scripts/build-master-picker.ts.",
        );
      }
    }
    console.log("PASS: MCP Master picker matches the shared UI and assets.");
  } else {
    const bundled = await new Deno.Command(Deno.execPath(), {
      args: [
        "bundle",
        "--no-config",
        "--platform=browser",
        "--format=iife",
        entry.pathname.replace(/^\/(\w:)/, "$1"),
      ],
      stdout: "piped",
      stderr: "piped",
    }).output();
    if (!bundled.success) throw new Error(decoder.decode(bundled.stderr));
    let script = decoder.decode(bundled.stdout);
    const sharedAssets: Record<string, string> = {};
    for (const [url, bytes] of inputs) {
      if (!url.includes("/src/assets/")) continue;
      let binary = "";
      for (const byte of bytes) binary += String.fromCharCode(byte);
      const mime = url.endsWith(".png")
        ? "image/png"
        : url.endsWith(".mp3")
        ? "audio/mpeg"
        : "image/jpeg";
      sharedAssets[
        new URL(url).pathname.slice(new URL(root).pathname.length - 1)
      ] = `data:${mime};base64,${btoa(binary)}`;
    }
    sharedAssets["__MCP_SHARED_FONTS__"] = decoder.decode(
      inputs.get(new URL("src/css/game-fonts.css", root).href),
    );
    // The game dependency graph includes the picker plus audio. Write the union once.
    if (game) {
      await Deno.writeTextFile(
        new URL(
          "supabase/functions/game-mcp/resource-ui-assets.generated.ts",
          root,
        ),
        stamp +
          "// GENERATED by scripts/build-master-picker.ts. Shared binary assets and fonts.\nexport const UI_ASSETS = " +
          JSON.stringify(sharedAssets) + ";\n",
      );
    }
    const css = styles.map((name) =>
      name === "src/css/game-fonts.css"
        ? "__MCP_SHARED_FONTS__"
        : decoder.decode(inputs.get(new URL(name, root).href))
    ).join("\n").replace(/@import\s+url\("\.\/master-picker.css"\);/g, "");
    const page = decoder.decode(inputs.get(new URL("game.html", root).href));
    const fonts =
      page.match(/<link href="https:\/\/fonts.googleapis.com[^>]+>/)?.[0] || "";
    const body = game
      ? page.match(/<main[\s\S]*?<\/main>/)?.[0]?.replace(
        "</main>",
        '<p id="game-status" role="status" hidden></p><button id="game-retry" hidden>Try again</button></main>',
      )
      : "";
    if (game && !body) throw new Error("Could not read the shared game shell.");
    const html =
      `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">${fonts}<style>${css}\nbody{min-height:0;padding:20px}main{max-width:720px;margin:auto}h1{font-size:22px}#status,#countdown{color:var(--muted);line-height:1.5}#retry{padding:10px;cursor:pointer}</style></head><body class="game-page"><main><h1>Choose your Master</h1><p id="status" role="status">Loading Masters…</p><p id="countdown"></p><div id="master-picker"></div><button id="retry" hidden>Try again</button></main><script>${
        script.replaceAll("</script", "<\\/script")
      }</script></body></html>`;
    const gameHtml =
      `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">${fonts}<style>${css}</style></head><body class="game-page">${body}<script>${
        script.replaceAll("</script", "<\\/script")
      }</script></body></html>`;
    await Deno.writeTextFile(
      output,
      stamp +
        "// GENERATED by scripts/build-master-picker.ts; edit the shared UI and MCP adapters.\nimport { UI_ASSETS } from './resource-ui-assets.generated.ts';\nexport const " +
        (game ? "GAME_HTML" : "MASTER_PICKER_HTML") + " = " +
        "Object.entries(UI_ASSETS).reduce((html, [path, data]) => html.replaceAll(path, data), " +
        JSON.stringify(game ? gameHtml : html) + ");\n",
    );
    console.log(
      "Built the MCP Master picker from the shared website components.",
    );
  }
}
export async function buildGame(check = false) {
  await buildMasterPicker(check, true);
}
if (import.meta.main) {
  await buildMasterPicker(Deno.args.includes("--check"));
  await buildGame(Deno.args.includes("--check"));
}
