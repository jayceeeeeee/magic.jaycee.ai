# Pin the existing Google Fonts so both website and MCP render without network fonts.
$ErrorActionPreference = 'Stop'
$taskRoot = Split-Path $PSScriptRoot -Parent
$fontFaces = @(
  @{Family='Rajdhani'; Weight=500; Url='https://fonts.gstatic.com/s/rajdhani/v17/LDI2apCSOBg7S-QT7pb0EMOs.ttf'},
  @{Family='Rajdhani'; Weight=600; Url='https://fonts.gstatic.com/s/rajdhani/v17/LDI2apCSOBg7S-QT7pbYF8Os.ttf'},
  @{Family='Rajdhani'; Weight=700; Url='https://fonts.gstatic.com/s/rajdhani/v17/LDI2apCSOBg7S-QT7pa8FsOs.ttf'},
  @{Family='Share Tech Mono'; Weight=400; Url='https://fonts.gstatic.com/s/sharetechmono/v16/J7aHnp1uDWRBEqV98dVQztYldFc7pA.ttf'}
)
$fontCss = '/* Generated by scripts/sync-game-fonts.ps1. SIL Open Font License: licenses/fonts/. */' + "`n"
foreach ($face in $fontFaces) {
  $response = Invoke-WebRequest -Uri $face.Url -UseBasicParsing
  $bytes = $response.RawContentStream.ToArray()
  if ($bytes.Length -lt 1000 -or $bytes.Length -gt 1000000) { throw 'Unexpected font size' }
  $base64 = [Convert]::ToBase64String($bytes)
  $fontCss += "@font-face{font-family:'$($face.Family)';font-style:normal;font-weight:$($face.Weight);font-display:swap;src:url(data:font/ttf;base64,$base64) format('truetype')}" + "`n"
}
[IO.File]::WriteAllText((Join-Path $taskRoot 'src/css/game-fonts.css'), $fontCss, [Text.UTF8Encoding]::new($false))
$licenseDir = Join-Path $taskRoot 'licenses/fonts'
New-Item -ItemType Directory -Path $licenseDir -Force | Out-Null
foreach ($family in @('rajdhani','sharetechmono')) {
  Invoke-WebRequest -Uri "https://raw.githubusercontent.com/google/fonts/main/ofl/$family/OFL.txt" -UseBasicParsing -OutFile (Join-Path $licenseDir "$family-OFL.txt")
}
Write-Output 'Synced the shared game fonts and licenses.'
